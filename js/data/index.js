/** Expected outputs for every problem, generated by `npm run build:expected`. */
export async function loadExpected() {
  const response = await fetch(new URL('./expected.json', import.meta.url));
  if (!response.ok) {
    throw new Error(`could not load expected.json (HTTP ${response.status}) — run "npm run build:expected"`);
  }
  return response.json();
}
